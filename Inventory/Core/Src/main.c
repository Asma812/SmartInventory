void send_data_to_nodemcu(uint8_t* rfid_data, char* classification_results) {
    uint8_t uart_frame[RFID_DATA_SIZE + CLASSIFICATION_RESULT_SIZE + 2];
    uart_frame[0] = 0xAA; // Start of Frame marker
    memcpy(&uart_frame[1], rfid_data, RFID_DATA_SIZE);
    uart_frame[RFID_DATA_SIZE + 1 + CLASSIFICATION_RESULT_SIZE] = 0x55; // End of Frame marker

    HAL_UART_Transmit(&huart2, uart_frame, sizeof(uart_frame), HAL_MAX_DELAY);
}

float* read_image_file(const char* filename) {
    FILE* file = fopen(filename, "rb");
    if (!file) {
        printf("Error opening file: %s\n", strerror(errno));
        return NULL;
    }

    fseek(file, 0, SEEK_END);
    long file_size = ftell(file);
    fseek(file, 0, SEEK_SET);

    float* image_data = (float*)malloc(file_size);
    if (!image_data) {
        fclose(file);
        printf("Error allocating memory\n");
        return NULL;
    }

    size_t bytes_read = fread(image_data, 1, file_size, file);
    fclose(file);

    if (bytes_read != file_size) {
        free(image_data);
        printf("Error reading file\n");
        return NULL;
    }

    return image_data;
}
